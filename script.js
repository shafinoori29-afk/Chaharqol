function showSurah(name) {
    const surah = surahs[name];

    document.getElementById("home").style.display = "none";
    document.getElementById("reader").style.display = "block";
    document.getElementById("surahTitle").textContent = surah.title;

    const container = document.getElementById("surahText");

    container.innerHTML = `
        <div class="bismillah">
            بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ
            <p>به نام خداوند بخشنده مهربان</p>
        </div>
        ${surah.ayahs.map((ayah, index) => `
            <div class="ayah-card">
                <div class="arabic">${ayah[0]} ﴿${index + 1}﴾</div>
                <div class="translation">${ayah[1]}</div>
            </div>
        `).join("")}
    `;

    window.scrollTo(0, 0);
}

function goHome() {
    document.getElementById("reader").style.display = "none";
    document.getElementById("home").style.display = "grid";
    window.scrollTo(0, 0);
}